# reusing the single most-recent DB reading pairs a stale queue-state value
# with an unrelated hour_of_day/calendar context the model never saw
# together in training — an out-of-distribution combination that produces
# unstable, sometimes wildly extrapolated predictions (observed: negative
# and >2x-the-training-cap outputs for the same combo at different
# requested hours, all sharing one stale people_waiting reading). Beyond
# this window, people_waiting falls back to baseline instead.
