TARGET_DESK_UTILIZATION = 0.7

# --------------------------------------------------------------------------
# Intraday expansion for derived proxy rows (pipeline/demand_baseline.py)
#
# The real dataset has no intra-day timestamp, so anchoring every daily
# proxy row at one flat clock time would give `hour_of_day` zero variance
# across the entire proxy dataset. Instead each day is expanded into
# representative daypart snapshots: (hour, minute, volume_factor), where
# volume_factor scales the day's average hourly attendance rate (factors
# average to 1.0 across a "typical" day). Each snapshot's wait-time estimate
# uses SNAPSHOT_WINDOW_HOURS (~1 hour), not the full day, as the M/M/1
# capacity window, since a snapshot represents an hour-scale slice of
# demand, not the whole day's total — reusing the full-day operating-hours
# constant here would make capacity look ~8x too large and understate wait
# times at every snapshot.
#
# Densified from 3 to 8 (one per business hour, 9:30-16:30, matching
# OPERATING_HOURS_PER_DAY=8.0) on 2026-07-27: with only 3 anchors, a
# same-week day-of-week ranking that was correct at 12:30 came out
# scrambled at 10-11am on the identical branch/service — the model had
# real support at exactly 3 clock times and was extrapolating everywhere
# else. This is still a documented approximation, not measured ground
# truth (a bell-ish ramp-up/peak/wind-down shape), just at finer
# resolution than before.
#
# !! OPEN FINDING (2026-07-30): REAL DATA SUGGESTS THIS CURVE IS INVERTED.
# The first real intra-day evidence this project has ever had -- live SIGA
# `people_waiting` counts, which (unlike tempoRealEspera) show no sign of
# the stale-counter pathology -- disagrees with the shape below, strongly.
# Normalized per (branch, service) to remove composition bias, across 71
# branches, by LOCAL (Europe/Lisbon) hour:
#     hour   assumed   observed
#      9      0.70      1.33
#     10      0.85      1.67   <- real peak
#     11      1.00      1.39
#     12      1.35      0.88
#     13      1.35      0.63   <- real trough
#     14      1.10      0.72
# Pearson correlation between assumed and observed: -0.79. The assumed
# peak (12-13h) is close to the observed *quietest* hour. Ask the model
# "what's the best hour to go" today and it will confidently recommend
# roughly the busiest real time, because this curve is what generated the
# hour_of_day signal in ~6.9M historical_derived_proxy training labels --
# so it is baked into the bulk of the training data, not just inference.
#
# NOT yet acted on, deliberately: only ~3 days of live data back this, and
# one innocent explanation isn't ruled out -- a midday dip in
# `people_waiting` could reflect staff lunch breaks cutting capacity
# rather than genuinely lower demand (the factors below are meant to
# represent demand volume). Recalibrating is also high-blast-radius: it
# regenerates every proxy label (pipeline/demand_baseline.py) and would
# invalidate the fitted output of pipeline/calibrate_constants.py, which
# was calibrated against labels built from the current factors. Revisit
# once several more weeks of live coverage exist; recalibrate against real
# people_waiting rather than re-guessing the shape by hand.
# --------------------------------------------------------------------------
DIURNAL_SNAPSHOTS: tuple[tuple[int, int, float], ...] = (
    (9, 30, 0.70),   # opening ramp-up
    (10, 30, 0.85),
    (11, 30, 1.00),
    (12, 30, 1.35),  # midday peak
    (13, 30, 1.35),  # midday peak continues
    (14, 30, 1.10),
    (15, 30, 0.85),
    (16, 30, 0.80),  # closing wind-down
)
SNAPSHOT_WINDOW_HOURS = 1.0

# --------------------------------------------------------------------------
# Proxy-vs-live sample weighting (pipeline/train.py)
#
# Once live SIGA scraping accumulates real samples for a given
# (branch_id, desk_service_id), that combo's historical_derived_proxy rows
# should count for less during training — but a global "drop all proxy data"
# cutover is wrong: real coverage will be extremely uneven across ~2,000
# distinct combos, so a global switch would blind whichever combos haven't
# accumulated live data yet. Instead each proxy row's weight decays per its
# own combo's live sample count: w = 1 / (1 + alpha * live_count). At
# live_count=0 (true today — no live scraping has run yet) w=1.0, i.e. this
# is a no-op until live data actually exists.
#
# RAISED 0.05 -> 0.5 on 2026-07-31, because 0.05 was far too weak to matter.
# Measured at that point: siga_live held 39,904 rows against 6.89M proxy
# rows, so despite carrying weight 1.0 per row it was **0.77% of total
# training weight**. The model was being fit toward a weighted mean target
# of 5.53 min while real live waits averaged 44.53 — and a forward test
# (pipeline/forward_test.py) showed exactly that signature: predicted mean
# 28.5 against an actual 41.2, i.e. systematic under-prediction, which for
# a citizen-facing wait estimate is the more damaging direction of error.
#
# The decay was too slow to bite at ANY realistic coverage level. On the
# best-covered combo in the whole dataset (65 live samples) a proxy row had
# still only decayed to 0.235, leaving proxy outweighing live 19:1 there.
# That also explains why the under-prediction looked uniform across
# well-covered and sparse combos alike — proxy dominates both, so uniformity
# was evidence FOR proxy dominance, not against it.
#
# 0.5 brings that same best-covered combo to roughly 2.4:1 rather than
# flipping it live-dominant — deliberately conservative, since ~30% of live
# readings are still of questionable quality (see
# REAL_DATA_MAX_PLAUSIBLE_WAIT_MINUTES above) and should not be trusted to
# outvote everything else outright.
#
# WHY THIS IS SAFE FOR LOW-COVERAGE COMBOS, which is the obvious worry:
# weight is 1/(1 + alpha*live_count), so a combo with zero live samples
# keeps weight exactly 1.0 for ANY alpha. Raising alpha can only ever affect
# combos that have earned real coverage — it is not a global down-weighting,
# and the ~1,500 combos relying solely on proxy data are untouched by
# construction. pipeline/forward_test.py's coverage split exists to verify
# that invariant empirically after any change here: the sparse segment must
# come out unchanged.
# --------------------------------------------------------------------------
PROXY_WEIGHT_DECAY_ALPHA = 0.5

# --------------------------------------------------------------------------
# historical_real_daily_avg reliability weighting (pipeline/train.py)
#
# IALC-M branch-day averages (pipeline/ingest_real_wait_times.py) are real
# measurements, but some branch-days carry very low Total_Atendimentos
# (occasionally 1 — see the SLC-M/IALC-M cross-check, 2026-07-27), making
